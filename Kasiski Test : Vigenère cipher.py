# 4. РАСШИФРОВКА ТЕКСТА
# ==========================================
def apply_key(text, key):
    result = ""
    for i, char in enumerate(text):
        if char in ALPHABET:
            text_idx = ALPHABET.index(char)
            key_idx = ALPHABET.index(key[i % len(key)])
            decrypted_idx = (text_idx - key_idx) % N
            result += ALPHABET[decrypted_idx]
        else:
            result += char
    return result

