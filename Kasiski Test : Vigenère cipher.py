# 3. ВЗЛОМ ВИЖЕНЕРА ЧАСТОТНЫМ АНАЛИЗОМ
# ==========================================
def decrypt_vigenere(text, key_len=4):
    print(f"=== ЭТАП 2: ВЗЛОМ СТОЛБЦОВ (Длина ключа = {key_len}) ===")
    key = ""
    
    # Разбиваем текст на столбцы по длине ключа
    for col in range(key_len):
        block = text[col::key_len]
        
        max_score = -1e9
        best_char = 'А'
        
        # Перебираем все 33 возможные буквы алфавита для этого столбца
        for shift in range(N):
            score = 0
            # Дешифруем столбец текущим сдвигом и оцениваем логарифмом вероятности
            for char in block:
                if char in ALPHABET:
                    char_idx = ALPHABET.index(char)
                    decrypted_idx = (char_idx - shift) % N
                    decrypted_char = ALPHABET[decrypted_idx]
                    score += math.log(FREQS.get(decrypted_char, 1e-10))
                    
            if score > max_score:
                max_score = score
                best_char = ALPHABET[shift]
                
        key += best_char
        print(f"Символ {col + 1} ключа: '{best_char}' (Сдвиг: {ALPHABET.index(best_char)})")
        
    print(f"\n[УСПЕХ] Найденный ключ: '{key}'\n")
    return key

