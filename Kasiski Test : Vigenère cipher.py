# 2. ТЕСТ КАЗИСКИ (Анализ расстояний)
# ==========================================
def kasiski_test(text):
    print("=== ЭТАП 1: ТЕСТ КАЗИСКИ ===")
    seq_spacings = {}
    # Ищем все повторяющиеся куски длиной 3 символа
    for i in range(len(text) - 2):
        seq = text[i:i+3]
        if seq not in seq_spacings:
            seq_spacings[seq] = []
        seq_spacings[seq].append(i)
        
    distances = []
    for seq, positions in seq_spacings.items():
        if len(positions) > 1:
            for i in range(len(positions) - 1):
                distances.append(positions[i+1] - positions[i])
                
    # Считаем, какие делители встречаются чаще всего
    factors_count = Counter()
    for d in distances:
        for i in range(2, 11):
            if d % i == 0:
                factors_count[i] += 1
                
    print("Найдены повторяющиеся последовательности.")
    print("Самые вероятные длины ключа (по частоте общих делителей):")
    for factor, count in factors_count.most_common(3):
        print(f"Длина {factor}: встретилась {count} раз")
    print("-" * 40 + "\n")

